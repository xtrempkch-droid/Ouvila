static const char *const *tabela(int lang)
{
    switch (lang) {
    case WM_LANG_EN:
        return EN;
    case WM_LANG_ZH:
        return ZH;
    case WM_LANG_HI:
        return HI;
    case WM_LANG_ES:
        return ES;
    case WM_LANG_AR:
        return AR;
    case WM_LANG_BN:
        return BN;
    case WM_LANG_ID:
        return ID;
    case WM_LANG_UR:
        return UR;
    case WM_LANG_FR:
        return FR;
    default:
        return PT;
    }
}

const char *wm_str(int id)
{
    const char *s;

    if (id < 0 || id >= MSG_TOTAL) {
        return "";
    }
    s = tabela(g_lang)[id];
    if (!s) {
        s = PT[id];
    }
    return s ? s : "";
}

int wm_lang(void)
{
    return g_lang;
}

void wm_lang_set(int id)
{
    if (id < 0 || id >= WM_LANG_TOTAL) {
        id = WM_LANG_PT;
    }
    g_lang = id;
}

const char *wm_lang_code(int id)
{
    if (id < 0 || id >= WM_LANG_TOTAL) {
        return "pt";
    }
    return LANGS[id].codigo;
}

int wm_lang_from_code(const char *code)
{
    if (!code || !code[0]) {
        return WM_LANG_PT;
    }
    for (int i = 0; i < WM_LANG_TOTAL; i++) {
        if (wm_casecmp(code, LANGS[i].codigo) == 0) {
            return i;
        }
    }
    /* Aceita variantes como "pt_BR" / "pt-BR". */
    for (int i = 0; i < WM_LANG_TOTAL; i++) {
        size_t n = strlen(LANGS[i].codigo);

        if (strncmp(code, LANGS[i].codigo, n) == 0
            && (code[n] == '_' || code[n] == '-' || code[n] == '\0')) {
            return i;
        }
    }
    return WM_LANG_PT;
}

const char *wm_lang_nome(int id)
{
    if (id < 0 || id >= WM_LANG_TOTAL) {
        return LANGS[WM_LANG_PT].nome;
    }
    return LANGS[id].nome;
}

bool wm_lang_rtl(void)
{
    return g_lang == WM_LANG_AR || g_lang == WM_LANG_UR;
}
