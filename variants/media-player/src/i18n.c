/* i18n.c — textos da UI em 10 idiomas.
 *
 * Por que uma tabela em C e não um arquivo .mo: o app é um binário só e não pode
 * depender de gettext no rootfs. A tabela é indexada pelo enum MSG_* do wm.h e
 * usa *designated initializers* — se faltar uma tradução ela fica NULL e o texto
 * cai no português (`wm_str`), em vez de imprimir ponteiro inválido.
 *
 * Os idiomas são os que o usuário pediu: inglês, chinês mandarim, hindi,
 * espanhol, árabe padrão moderno, bengali, indonésio, urdu, francês e português
 * do Brasil.
 *
 * Nota sobre alfabetos: estes textos só aparecem corretamente porque o app
 * carrega fontes de reserva (Noto) e passa o texto pelo HarfBuzz (ver font.c).
 * Árabe e urdu precisam de junção de letras; hindi e bengali, de reordenação de
 * vogais. FreeType sozinho não faz nenhuma das duas coisas.
 */

